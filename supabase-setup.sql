create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  email text not null,
  photo_url text,
  created_at timestamptz not null default now()
);

alter table public.registrations enable row level security;
grant insert on public.registrations to anon;
grant insert, select on public.registrations to authenticated;
drop policy if exists "Public can submit registrations" on public.registrations;
create policy "Public can submit registrations" on public.registrations for insert to anon with check (true);
drop policy if exists "Approved users can submit registrations" on public.registrations;
create policy "Approved users can submit registrations" on public.registrations for insert to authenticated with check (true);

create or replace view public.registered_members as
select id, name, photo_url, created_at from public.registrations;
revoke select on public.registered_members from anon;
grant select on public.registered_members to authenticated;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.admin_users enable row level security;
grant select on public.admin_users to authenticated;
drop policy if exists "Admins can view their allowlist record" on public.admin_users;
create policy "Admins can view their allowlist record" on public.admin_users for select to authenticated using (user_id = auth.uid());

create table if not exists public.daily_performance (
  id bigint generated by default as identity primary key,
  member_key text not null,
  member_id text,
  member_name text not null,
  department_id text,
  department_name text,
  performance_date date not null,
  attendance boolean not null default false,
  daily_score numeric(5, 2) not null check (daily_score >= 0 and daily_score <= 100),
  remarks text,
  created_at timestamptz not null default now(),
  unique (member_key, performance_date)
);

alter table public.daily_performance add column if not exists member_id text;
alter table public.daily_performance add column if not exists department_id text;
alter table public.daily_performance add column if not exists department_name text;
alter table public.daily_performance add column if not exists remarks text;
alter table public.daily_performance enable row level security;
grant select on public.daily_performance to anon, authenticated;
grant insert, update, delete on public.daily_performance to authenticated;

drop policy if exists "Public can view daily performance" on public.daily_performance;
create policy "Public can view daily performance" on public.daily_performance for select to anon using (true);
drop policy if exists "Admins can view daily performance" on public.daily_performance;
create policy "Admins can view daily performance" on public.daily_performance for select to authenticated using (exists (select 1 from public.admin_users where user_id = auth.uid()));
drop policy if exists "Admins can insert daily performance" on public.daily_performance;
create policy "Admins can insert daily performance" on public.daily_performance for insert to authenticated with check (exists (select 1 from public.admin_users where user_id = auth.uid()));
drop policy if exists "Admins can update daily performance" on public.daily_performance;
create policy "Admins can update daily performance" on public.daily_performance for update to authenticated using (exists (select 1 from public.admin_users where user_id = auth.uid())) with check (exists (select 1 from public.admin_users where user_id = auth.uid()));
drop policy if exists "Admins can delete daily performance" on public.daily_performance;
create policy "Admins can delete daily performance" on public.daily_performance for delete to authenticated using (exists (select 1 from public.admin_users where user_id = auth.uid()));

